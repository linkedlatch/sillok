"""Writes the tables the Qwen backend splits text for Qwen3-ForcedAligner with.

Usage: python3 -I scripts/backends/qwen_tables.py KOREAN_DICT
KOREAN_DICT is qwen_asr/inference/assets/korean_dict_jieba.dict of the
qwen-asr package at QWEN_ASR_VERSION (pip install qwen-asr==0.0.6; Apache
2.0), checked against KOREAN_DICT_SHA256. Writes
  src/backends/qwen/korean_dict.inc  the words of the dictionary (its first
                                     column), sorted by their UTF-8 bytes
  src/backends/qwen/word_chars.inc   the code point ranges of the Unicode
                                     general categories L* and N*, from
                                     DerivedGeneralCategory.txt of Unicode
                                     UNICODE_VERSION
Run it again after changing either version.
"""
import hashlib
import os
import re
import sys
import urllib.request

QWEN_ASR_VERSION = "0.0.6"
KOREAN_DICT_SHA256 = "cc157a9ab78f92bf11ed98a69b285768d6627cf5cd57a581e6c06693effce37d"
UNICODE_VERSION = "18.0.0"
URL = "https://www.unicode.org/Public/{version}/ucd/extracted/DerivedGeneralCategory.txt"

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT_DIR = os.path.join(ROOT, "src", "backends", "qwen")


def c_string(text):
    """A C++ string literal of `text`, kept as UTF-8 (sources compile as UTF-8)."""
    if '"' in text or "\\" in text or any(ord(ch) < 0x20 for ch in text):
        sys.exit(f"unexpected character in {text!r}")
    return '"' + text + '"'


def korean_dict(path):
    with open(path, "rb") as file:
        data = file.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != KOREAN_DICT_SHA256:
        sys.exit(f"{path}: SHA-256 {digest}, expected {KOREAN_DICT_SHA256} (qwen-asr {QWEN_ASR_VERSION})")
    words = {line.split()[0] for line in data.decode("utf-8").splitlines() if line.strip()}
    words = sorted(words, key=lambda w: w.encode("utf-8"))
    lines = [
        "// Words of korean_dict_jieba.dict of qwen-asr " + QWEN_ASR_VERSION + " (Apache 2.0), which",
        "// Qwen3-ForcedAligner's processor splits Korean words with, sorted by",
        "// their UTF-8 bytes. Generated by scripts/backends/qwen_tables.py; do not edit.",
    ]
    for i in range(0, len(words), 8):
        lines.append("    " + " ".join(c_string(w) + "," for w in words[i:i + 8]))
    with open(os.path.join(OUT_DIR, "korean_dict.inc"), "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines) + "\n")
    return len(words)


def word_chars():
    with urllib.request.urlopen(URL.format(version=UNICODE_VERSION), timeout=60) as response:
        text = response.read().decode("utf-8")
    found = []
    for line in text.splitlines():
        match = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([LN][a-z])\b", line)
        if match:
            first = int(match.group(1), 16)
            found.append((first, int(match.group(2) or match.group(1), 16)))
    if len(found) < 500:
        sys.exit(f"only {len(found)} letter and number ranges found")
    found.sort()
    merged = [found[0]]
    for first, last in found[1:]:
        if first == merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], last)
        else:
            merged.append((first, last))
    lines = [
        "// Code point ranges {first, last} of the Unicode general categories L*",
        "// (letters) and N* (numbers), sorted. Generated by",
        f"// scripts/backends/qwen_tables.py from Unicode {UNICODE_VERSION}; do not edit.",
    ]
    items = [f"{{0x{a:04X}, 0x{b:04X}}}," for a, b in merged]
    for i in range(0, len(items), 6):
        lines.append("    " + " ".join(items[i:i + 6]))
    with open(os.path.join(OUT_DIR, "word_chars.inc"), "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines) + "\n")
    return len(merged)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    os.makedirs(OUT_DIR, exist_ok=True)
    print(f"{korean_dict(sys.argv[1])} Korean words, {word_chars()} letter and number ranges -> {OUT_DIR}")


if __name__ == "__main__":
    main()
