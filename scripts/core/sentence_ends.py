"""Writes the table of characters that end a sentence.

Usage: python3 -I scripts/core/sentence_ends.py
Downloads PropList.txt of the Unicode Character Database at UNICODE_VERSION
and writes src/core/sentence_ends.inc: the ranges of code points with the
Sentence_Terminal property (UAX #29: . ! ? and their counterparts in other
scripts, such as 。 । ؟ ။). Run it again after changing UNICODE_VERSION.
"""
import os
import re
import urllib.request

UNICODE_VERSION = "18.0.0"
URL = "https://www.unicode.org/Public/{version}/ucd/PropList.txt"

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUTPUT = os.path.join(ROOT, "src", "core", "sentence_ends.inc")


def ranges():
    with urllib.request.urlopen(URL.format(version=UNICODE_VERSION), timeout=60) as response:
        text = response.read().decode("utf-8")
    found = []
    for line in text.splitlines():
        match = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*Sentence_Terminal\b", line)
        if match:
            first = int(match.group(1), 16)
            found.append((first, int(match.group(2) or match.group(1), 16)))
    if len(found) < 50:
        raise SystemExit(f"only {len(found)} Sentence_Terminal ranges found")
    found.sort()
    merged = [found[0]]
    for first, last in found[1:]:
        if first == merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], last)
        else:
            merged.append((first, last))
    return merged


def main():
    table = ranges()
    lines = [
        "// Code point ranges {first, last} with the Unicode Sentence_Terminal",
        f"// property, sorted. Generated by scripts/core/sentence_ends.py from",
        f"// PropList.txt of Unicode {UNICODE_VERSION}; do not edit.",
    ]
    items = [f"{{0x{a:04X}, 0x{b:04X}}}," for a, b in table]
    for i in range(0, len(items), 6):
        lines.append("    " + " ".join(items[i:i + 6]))
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines) + "\n")
    print(f"{len(table)} ranges, {sum(b - a + 1 for a, b in table)} code points -> {OUTPUT}")


if __name__ == "__main__":
    main()
