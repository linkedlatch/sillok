"""Writes the app's names of the languages sillok transcribes.

Usage: python3 -I scripts/app/language_names.py
Reads the language codes from the catalog (src/backends/models.cpp) and the
app's own languages from its translations (apps/app/lib/l10n/app_<code>.arb),
downloads from Unicode CLDR at CLDR_VERSION the names of those languages in
each of the app's and in each language itself, and writes
apps/app/lib/ui/language_names.g.dart. Run it again after changing the
languages, adding a translation of the app or changing CLDR_VERSION.
"""
import json
import os
import re
import sys
import urllib.error
import urllib.request

CLDR_VERSION = "49.0.0"
CLDR_URL = ("https://raw.githubusercontent.com/unicode-org/cldr-json/{version}/cldr-json/"
            "cldr-localenames-full/main/{locale}/languages.json")

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MODELS = os.path.join(ROOT, "src", "backends", "models.cpp")
L10N = os.path.join(ROOT, "apps", "app", "lib", "l10n")
OUTPUT = os.path.join(ROOT, "apps", "app", "lib", "ui", "language_names.g.dart")


def catalog_codes():
    """The catalog's language codes, in its own order."""
    with open(MODELS, encoding="utf-8") as file:
        source = file.read()
    match = re.search(r"static const std::vector<std::string> languages = \{([^}]*)\}", source)
    if match is None:
        sys.exit(f"found no languages in {MODELS}")
    return re.findall(r'"([a-z]+)"', match.group(1))


def app_locales():
    locales = sorted(re.fullmatch(r"app_(\w+)\.arb", name).group(1)
                     for name in os.listdir(L10N) if re.fullmatch(r"app_\w+\.arb", name))
    if "en" not in locales:
        sys.exit("the app has no English translation")
    return locales


def cldr_names(locale, required=True):
    """Language names in `locale`; None when CLDR has no such locale and
    they are not `required`."""
    url = CLDR_URL.format(version=CLDR_VERSION, locale=locale)
    try:
        with urllib.request.urlopen(url, timeout=60) as response:
            data = json.load(response)
    except urllib.error.HTTPError as error:
        if error.code == 404 and not required:
            return None
        raise
    return data["main"][locale]["localeDisplayNames"]["languages"]


def self_name(code):
    """What the language calls itself, or None when CLDR does not say."""
    names = cldr_names(code, required=False)
    return names.get(code) if names else None


def dart_string(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def main():
    codes = catalog_codes()
    lines = [
        f"// Generated by scripts/app/language_names.py from Unicode CLDR {CLDR_VERSION}; do not edit.",
        "",
        "/// Names of the languages sillok transcribes, by the app's language and",
        "/// then by code.",
        "const languageNames = <String, Map<String, String>>{",
    ]
    for locale in app_locales():
        names = cldr_names(locale)
        lines.append(f"  {dart_string(locale)}: {{")
        for code in codes:
            name = names.get(code)
            if name is None:
                sys.exit(f"CLDR {CLDR_VERSION} has no {locale} name for {code}")
            lines.append(f"    {dart_string(code)}: {dart_string(name)},")
        lines.append("  },")
    lines.append("};")
    lines += [
        "",
        "/// What each language calls itself, where CLDR says.",
        "const languageSelfNames = <String, String>{",
    ]
    missing = []
    for code in codes:
        name = self_name(code)
        if name is None:
            missing.append(code)
        else:
            lines.append(f"  {dart_string(code)}: {dart_string(name)},")
    lines.append("};")
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines) + "\n")
    print(f"wrote {len(codes)} languages in {len(app_locales())} app languages to {OUTPUT}; "
          f"no name of their own for {', '.join(missing) or 'none'}")


if __name__ == "__main__":
    main()
